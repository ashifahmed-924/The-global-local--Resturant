export function formatPrice(item) {
  if (item.price == null) return null;
  return new Intl.NumberFormat('en-AU', {
    style: 'currency',
    currency: item.currency || 'AUD',
  }).format(item.price);
}

export function itemsByCategory(categoryId) {
  const map = {
    breakfast: ['breakfast'],
    toasties: ['toasties'],
    wraps: ['wraps'],
    bakery: ['bakery', 'pies'],
    'hot-beverages': ['hot-beverages'],
    'cold-beverages': ['cold-beverages', 'juices'],
  };
  const cats = map[categoryId] || [categoryId];
  return menuItems.filter((item) => cats.includes(item.category));
}

export function getFeaturedForCategory(categoryId) {
  const items = itemsByCategory(categoryId);
  return items[0] || menuItems[0];
}
